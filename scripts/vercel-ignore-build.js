// Vercel Ignored Build Step Script
// Return 0 (exit 0) to CANCEL/SKIP the build in Vercel
// Return 1 (exit 1) to PROCEED with the build in Vercel

const commitMsg = process.env.VERCEL_GIT_COMMIT_MESSAGE || '';
const branch = process.env.VERCEL_GIT_COMMIT_REF || '';

console.log(`[Vercel Build Gate] Branch: "${branch}", Commit: "${commitMsg}"`);

// 1. If not building 'main' (e.g. preview branch or PR), always proceed
if (branch !== 'main') {
  console.log('[Vercel Build Gate] Preview/PR branch detected -> Proceeding with build.');
  process.exit(1);
}

// 2. If this is an automated release commit generated by GitHub Actions, proceed!
if (commitMsg.startsWith('chore(release):') || commitMsg.includes('[release-deploy]')) {
  console.log('[Vercel Build Gate] Release commit detected -> Proceeding with production deployment.');
  process.exit(1);
}

// 3. If this commit triggers a release (fix, feat, breaking), SKIP this build because
// GitHub Actions is already running and will push the bumped release commit within seconds!
const isReleaseTriggering =
  /^(fix|feat)(\(.*\))?:/i.test(commitMsg) ||
  /BREAKING[- ]CHANGE/i.test(commitMsg) ||
  /^[a-z]+(\([^\)]+\))?!:/i.test(commitMsg) ||
  /\[release:/i.test(commitMsg);

if (isReleaseTriggering) {
  console.log('[Vercel Build Gate] Release-triggering commit on main -> Skipping un-bumped build; waiting for GitHub Actions release commit.');
  process.exit(0);
}

// 4. For non-release commits (docs, style, refactor, chore), proceed normally
console.log('[Vercel Build Gate] Normal non-release commit -> Proceeding with build.');
process.exit(1);
